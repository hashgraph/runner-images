# Regenerates apk-packages.lock: the exact Wolfi package closure (name=version) that Dockerfile.chainguard installs
# on top of its digest-pinned base image, resolved from the packages listed in apk-packages.in.
#
# Wolfi has no point-in-time snapshot service, so every package, including transitive dependencies, is pinned
# explicitly. Re-run this after changing apk-packages.in or the base image digest, or to pick up newer builds.
#
# Requirements: docker, curl, and pull access to the base image registry (artifacts.hashgraph.io). Resolution runs
# natively in a wolfi-base container against an exported copy of the amd64 base root filesystem, so no amd64
# emulation is needed.

set -euo pipefail

RESOLVER_IMAGE="cgr.dev/chainguard/wolfi-base@sha256:2c12da5496e21e99003b3db3b9246f025e53d533c4df334205391260f1e8f85b"

cd "$(dirname "${BASH_SOURCE[0]}")"

base_image="$(awk '$1 == "FROM" && $NF == "base-dev" {print $2}' Dockerfile.chainguard)"
if [[ -z "${base_image}" ]]; then
  echo "error: could not find the base-dev stage image in Dockerfile.chainguard" >&2
  exit 1
fi

work="$(mktemp -d)"
cid=""
cleanup() {
  [[ -n "${cid}" ]] && docker rm -f "${cid}" >/dev/null 2>&1
  rm -rf "${work}"
}
trap cleanup EXIT

echo "Exporting ${base_image}"
cid="$(docker create --platform linux/amd64 "${base_image}")"
docker export "${cid}" >"${work}/rootfs.tar"
docker rm "${cid}" >/dev/null
cid=""

# The resolver's apk refuses the base image's cgr.dev repositories without HTTP_AUTH, while they serve anonymously.
# Mirror their indexes locally (signatures are still verified against the base image's keys) and resolve from those.
mkdir -p "${work}/mirror"
: >"${work}/repositories"
while read -r repo; do
  [[ -z "${repo}" || "${repo}" == \#* ]] && continue
  name="$(basename "${repo}")"
  mkdir -p "${work}/mirror/${name}/x86_64"
  echo "Fetching ${repo}/x86_64/APKINDEX.tar.gz"
  curl -fsSLo "${work}/mirror/${name}/x86_64/APKINDEX.tar.gz" "${repo}/x86_64/APKINDEX.tar.gz"
  echo "/mirror/${name}" >>"${work}/repositories"
done < <(tar -xOf "${work}/rootfs.tar" etc/apk/repositories)

packages() { awk -v step="$1" '$1 == step {for (i = 2; i <= NF; i++) print $i}' apk-packages.in | xargs; }

# Prints "name=version" for every package apk would install or upgrade on top of the base image.
cat >"${work}/resolve.sh" <<'EOF'
set -eu
mkdir /r
tar -xf /work/rootfs.tar -C /r 2>/dev/null || true
cp /work/repositories /r/etc/apk/repositories
apk --root /r --simulate --no-scripts --no-cache add "$@" |
  sed -nE 's/^\([0-9]+\/[0-9]+\) (Installing|Upgrading|Downgrading|Replacing) ([^ ]+) \((.* -> )?([^)]+)\)$/\2=\4/p' |
  sort
EOF

resolve() {
  docker run --rm -v "${work}:/work:ro" -v "${work}/mirror:/mirror:ro" "${RESOLVER_IMAGE}" \
    sh /work/resolve.sh "$@"
}

echo "Resolving package closures"
# shellcheck disable=SC2046 # word splitting of the package lists is intended
build="$(resolve $(packages build))"
# shellcheck disable=SC2046
system="$(resolve $(packages system))"
# shellcheck disable=SC2046
system_and_tools="$(resolve $(packages system) $(packages tools))"
tools="$(comm -13 <(echo "${system}") <(echo "${system_and_tools}"))"

# The tools step runs after the system step, so the system closure must resolve identically in both.
if [[ -n "$(comm -23 <(echo "${system}") <(echo "${system_and_tools}"))" ]]; then
  echo "error: the system packages resolve differently once the tools packages are added; resolve manually" >&2
  exit 1
fi

if [[ -z "${build}" || -z "${system}" || -z "${tools}" ]]; then
  echo "error: resolved an empty package set (build: ${build:-none}; system: ${system:-none}; tools: ${tools:-none})" >&2
  exit 1
fi

{
  echo "# Generated by update-apk-lock.sh from apk-packages.in. Do not edit by hand."
  echo "# Base image: ${base_image}"
  echo "#"
  echo "# Format: <step> <package>=<version> (full closure, including transitive dependencies)"
  awk '{print "build", $0}' <<<"${build}"
  awk '{print "system", $0}' <<<"${system}"
  awk '{print "tools", $0}' <<<"${tools}"
} >apk-packages.lock

echo "Wrote apk-packages.lock ($(grep -vc '^#' apk-packages.lock) pins)"
